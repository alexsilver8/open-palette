import { clipboard } from 'electron';
import type { ClipboardSource } from './history';

/**
 * Clipboard formats that apps add to say "don't record this": nspasteboard.org markers on
 * macOS (1Password, Bitwarden, …), the Windows clipboard-monitor opt-out, and KDE's
 * password-manager hint.
 */
const PRIVATE_FORMATS: Partial<Record<NodeJS.Platform, string[]>> = {
  darwin: ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType'],
  win32: ['ExcludeClipboardContentFromMonitorProcessing'],
  linux: ['x-kde-passwordManagerHint'],
};

export const electronClipboard: ClipboardSource = {
  readText: () => clipboard.readText(),
  async isConcealed() {
    const formats = PRIVATE_FORMATS[process.platform] ?? [];
    const present = await Promise.all(
      formats.map((format) => clipboard.has(`electron application/osclipboard;format="${format}"`).catch(() => false)),
    );
    return present.some(Boolean);
  },
};
